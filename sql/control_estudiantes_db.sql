CREATE DATABASE IF NOT EXISTS control_estudiantes_db CHARACTER SET utf8mb4;
USE control_estudiantes_db;

CREATE TABLE sexo (
    SEXOID VARCHAR(3) PRIMARY KEY,
    DESCRIPCION VARCHAR(50) NOT NULL
);

CREATE TABLE estado_civil (
    ESTADOCIVILID INT AUTO_INCREMENT PRIMARY KEY,
    DESCRIPCION VARCHAR(50) NOT NULL
);

CREATE TABLE ocupacion (
    OCUPACIONID INT AUTO_INCREMENT PRIMARY KEY,
    DESCRIPCION VARCHAR(100) NOT NULL
);

CREATE TABLE nacionalidad (
    NACIONALIDADID INT AUTO_INCREMENT PRIMARY KEY,
    DESCRIPCION VARCHAR(100) NOT NULL
);

CREATE TABLE regestudiante (
    ESTUDIANTEID INT AUTO_INCREMENT PRIMARY KEY,
    ASPIRANTEID INT NULL,
    CARNET VARCHAR(10) NOT NULL UNIQUE,
    PRIMERNOMBRE VARCHAR(100) NOT NULL,
    SEGUNDONOMBRE VARCHAR(100) NULL,
    PRIMERAPELLIDO VARCHAR(100) NOT NULL,
    SEGUNDOAPELLIDO VARCHAR(100) NULL,
    FECHANACIMIENTO DATETIME NULL,
    DIRECCION VARCHAR(200) NULL,
    TELEFONOFIJO VARCHAR(25) NULL,
    DUI VARCHAR(25) NULL UNIQUE,
    FECHACREACION DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MATRICULABACHILLERATO DECIMAL(18, 2) NULL,
    CUOTABACHILLERATO DECIMAL(18, 2) NULL,
    SEXOID VARCHAR(3) NULL,
    ESTADOCIVILID INT NULL,
    OCUPACIONID INT NULL,
    NACIONALIDADID INT NULL,

    CONSTRAINT fk_estudiante_sexo FOREIGN KEY (SEXOID) REFERENCES sexo(SEXOID),
    CONSTRAINT fk_estudiante_estadocivil FOREIGN KEY (ESTADOCIVILID) REFERENCES estado_civil(ESTADOCIVILID),
    CONSTRAINT fk_estudiante_ocupacion FOREIGN KEY (OCUPACIONID) REFERENCES ocupacion(OCUPACIONID),
    CONSTRAINT fk_estudiante_nacionalidad FOREIGN KEY (NACIONALIDADID) REFERENCES nacionalidad(NACIONALIDADID)
);

INSERT IGNORE INTO sexo (SEXOID, DESCRIPCION) VALUES ('M', 'Masculino'), ('F', 'Femenino');

INSERT INTO estado_civil (DESCRIPCION)
SELECT catalogo.DESCRIPCION
FROM (SELECT 'Soltero/a' AS DESCRIPCION
      UNION ALL SELECT 'Casado/a'
      UNION ALL SELECT 'Divorciado/a') AS catalogo
WHERE NOT EXISTS (
    SELECT 1 FROM estado_civil existente
    WHERE existente.DESCRIPCION = catalogo.DESCRIPCION
);

INSERT INTO ocupacion (DESCRIPCION)
SELECT catalogo.DESCRIPCION
FROM (SELECT 'Estudiante' AS DESCRIPCION
      UNION ALL SELECT 'Empleado'
      UNION ALL SELECT 'Desempleado') AS catalogo
WHERE NOT EXISTS (
    SELECT 1 FROM ocupacion existente
    WHERE existente.DESCRIPCION = catalogo.DESCRIPCION
);

INSERT INTO nacionalidad (DESCRIPCION)
SELECT catalogo.DESCRIPCION
FROM (SELECT 'Salvadoreña' AS DESCRIPCION
      UNION ALL SELECT 'Guatemalteca'
      UNION ALL SELECT 'Hondureña') AS catalogo
WHERE NOT EXISTS (
    SELECT 1 FROM nacionalidad existente
    WHERE existente.DESCRIPCION = catalogo.DESCRIPCION
);
